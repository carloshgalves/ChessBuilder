import {test,expect} from '@playwright/test'
test('free analysis explores independent branches and returns to original',async({page,request})=>{
 const result=await request.post('/api/import/pgn',{data:{pgn:'[White "ExploreFixture"]\n[Black "Opponent"]\n[Result "*"]\n\n1. e4 e5 *',username:'ExploreFixture'}})
 expect(result.ok()).toBeTruthy()
 const games=await (await request.get('/api/games?search=ExploreFixture')).json()
 await page.goto('/?game='+games[0].id)
 await page.getByRole('button',{name:'Análise livre',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Análise livre',exact:true})).toBeVisible()
 await page.locator('button[data-square="d2"]').click()
 await page.locator('button[data-square="d4"]').click()
 await expect(page.getByRole('button',{name:'1. d4',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Desfazer',exact:true}).click()
 await page.locator('button[data-square="e2"]').click()
 await page.locator('button[data-square="e4"]').click()
 await expect(page.getByRole('button',{name:'1. e4',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'← Voltar à partida original',exact:true}).click()
 await expect(page.getByRole('heading',{name:'ExploreFixture × Opponent'})).toBeVisible()
 await expect(page.getByRole('button',{name:'1. e4',exact:true})).toBeVisible()
})
