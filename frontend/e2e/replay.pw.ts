import {test,expect} from '@playwright/test'
test('replay shows game ratings and elapsed time and can autoplay',async({page,request})=>{
 const imported=await request.post('/api/import/pgn',{data:{username:'ReplayFixture',pgn:'[White "ReplayFixture"]\n[Black "ClockFixture"]\n[WhiteElo "1772"]\n[BlackElo "1820"]\n[TimeControl "300+5"]\n\n1. e4 {[%clk 0:04:58] [%emt 0:00:07]} e5 {[%clk 0:05:02]} 2. Nf3 {[%clk 0:04:53]} Nc6 {[%clk 0:04:59]} *'}})
 expect(imported.ok()).toBeTruthy()
 const list=await request.get('/api/games?search=ReplayFixture')
 expect(list.ok()).toBeTruthy()
 const games=await list.json()
 await page.goto('/?game='+games[0].id)
 await expect(page.locator('.replay-player-strip').filter({hasText:'ReplayFixture'})).toContainText('1772')
 await expect(page.locator('.replay-player-strip').filter({hasText:'ClockFixture'})).toContainText('1820')
 await expect(page.getByRole('button',{name:'1. e4',exact:true})).toContainText('7 s')
 await page.getByRole('button',{name:'2. Nf3',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Nf3',exact:true})).toBeVisible()
 await expect(page.locator('.replay-player-strip').filter({hasText:'ReplayFixture'})).toContainText('4:53')
 await page.getByLabel('Velocidade').selectOption('250')
 await page.getByRole('button',{name:'Reproduzir',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Nc6',exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'Reproduzir',exact:true})).toBeVisible()
})
